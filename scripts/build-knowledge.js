#!/usr/bin/env node
'use strict';
// Bundles the knowledge folder into netlify/lib/knowledge.generated.js so the
// functions can ship it without filesystem tricks. Runs on every Netlify build.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'netlify', 'lib', 'knowledge.generated.js');

function collect() {
  const files = [];
  const add = (rel) => {
    const content = fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n');
    files.push({ path: rel.split(path.sep).join('/'), content });
  };
  const listMd = (dir) => {
    const abs = path.join(ROOT, dir);
    if (!fs.existsSync(abs)) return [];
    return fs.readdirSync(abs)
      .filter((f) => /\.(md|txt)$/i.test(f) && f.toLowerCase() !== 'readme.md')
      .sort()
      .map((f) => path.join(dir, f));
  };
  // Fixed order keeps the prompt prefix byte stable, which keeps the cache warm.
  const derivedOrder = ['chart-legend.md', 'indicator-spec.md', 'glossary.md', 'rubric.md', 'conflicts.md'];
  for (const f of derivedOrder) {
    const rel = path.join('knowledge', 'derived', f);
    if (fs.existsSync(path.join(ROOT, rel))) add(rel);
  }
  for (const rel of listMd(path.join('knowledge', 'derived'))) {
    if (!derivedOrder.includes(path.basename(rel))) add(rel);
  }
  for (const rel of listMd(path.join('knowledge', 'study-notes'))) add(rel);
  return files;
}

function status(files) {
  const get = (p) => files.find((f) => f.path === p);
  const spec = get('knowledge/derived/indicator-spec.md');
  const legend = get('knowledge/derived/chart-legend.md');
  const indicatorDir = path.join(ROOT, 'knowledge', 'indicator');
  const indicatorFiles = fs.existsSync(indicatorDir)
    ? fs.readdirSync(indicatorDir).filter((f) => /\.(pine|txt)$/i.test(f)) : [];
  return {
    specPending: !spec || /NOT YET EXTRACTED/.test(spec.content),
    legendPending: !legend || /NOT YET EXTRACTED/.test(legend.content),
    glossaryProvisional: /PROVISIONAL/.test((get('knowledge/derived/glossary.md') || {}).content || ''),
    studyNotes: files.filter((f) => f.path.startsWith('knowledge/study-notes/')).length,
    indicatorFiles: indicatorFiles.length,
  };
}

function main() {
  const files = collect();
  const hash = crypto.createHash('sha256').update(JSON.stringify(files)).digest('hex').slice(0, 16);
  const out = `// GENERATED by scripts/build-knowledge.js. Do not edit by hand.\n'use strict';\nmodule.exports = ${JSON.stringify({ hash, status: status(files), files }, null, 2)};\n`;
  fs.writeFileSync(OUT, out);
  const total = files.reduce((a, f) => a + f.content.length, 0);
  console.log(`knowledge bundle ${hash}: ${files.length} files, ${total} chars -> ${path.relative(ROOT, OUT)}`);
}

if (require.main === module) main();
module.exports = { collect, status };
